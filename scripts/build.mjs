// Build: reads data/*.json (data model v1), checks every reference, writes data/bundle.js for the site.
// Usage: node scripts/build.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "data");
const COLLECTIONS = ["persons", "names", "life_events", "relations", "works", "work_contributors", "work_relations",
  "places", "person_places", "institutions", "person_institutions", "events", "person_events", "sources"];

const load = n => { const f = join(dir, n + ".json"); return existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : []; };
const db = Object.fromEntries(COLLECTIONS.map(n => [n, load(n)]));
const meta = existsSync(join(dir, "meta.json")) ? JSON.parse(readFileSync(join(dir, "meta.json"), "utf8")) : {};

const errors = [], warnings = [];
const ids = n => new Set(db[n].map(r => r.id));
const persons = ids("persons"), works = ids("works"), places = ids("places"), insts = ids("institutions"),
  events = ids("events"), sources = ids("sources");

const dup = n => { const seen = new Set(); for (const r of db[n]) { if (seen.has(r.id)) errors.push(`${n}: duplicate id ${r.id}`); seen.add(r.id); } };
["persons", "works", "places", "institutions", "events", "sources"].forEach(dup);

const need = (set, val, where) => { if (val != null && !set.has(val)) errors.push(`${where}: unknown reference "${val}"`); };
const cites = (r, where) => (r.citations || []).forEach(c => need(sources, c, where + " citation"));

for (const p of db.persons) { cites(p, `persons/${p.id}`);
  const ns = db.names.filter(n => n.person_id === p.id);
  if (!ns.some(n => n.type === "shuhra" && n.lang === "en")) errors.push(`persons/${p.id}: no English shuhra name`);
  if (!ns.some(n => n.type === "shuhra" && n.lang === "ar")) warnings.push(`persons/${p.id}: no Arabic-script shuhra name`); }
db.names.forEach((n, i) => { need(persons, n.person_id, `names[${i}]`); cites(n, `names[${i}]`); });
db.life_events.forEach((e, i) => { need(persons, e.person_id, `life_events[${i}]`); need(places, e.place_id, `life_events[${i}]`); cites(e, `life_events[${i}]`);
  if (e.date && e.date.sort == null) warnings.push(`life_events[${i}] (${e.person_id} ${e.type}): no sort key`); });
db.relations.forEach((r, i) => { need(persons, r.from, `relations[${i}].from`); need(persons, r.to, `relations[${i}].to`); need(places, r.place_id, `relations[${i}]`); cites(r, `relations[${i}]`); });
db.works.forEach(w => cites(w, `works/${w.id}`));
db.work_contributors.forEach((c, i) => { need(works, c.work_id, `work_contributors[${i}]`); need(persons, c.person_id, `work_contributors[${i}]`); });
db.work_relations.forEach((r, i) => { need(works, r.from, `work_relations[${i}]`); need(works, r.to, `work_relations[${i}]`); });
db.places.forEach(p => need(places, p.parent_id, `places/${p.id}`));
db.person_places.forEach((x, i) => { need(persons, x.person_id, `person_places[${i}]`); need(places, x.place_id, `person_places[${i}]`); cites(x, `person_places[${i}]`); });
db.institutions.forEach(x => { need(places, x.place_id, `institutions/${x.id}`); cites(x, `institutions/${x.id}`); });
db.person_institutions.forEach((x, i) => { need(persons, x.person_id, `person_institutions[${i}]`); need(insts, x.institution_id, `person_institutions[${i}]`); cites(x, `person_institutions[${i}]`); });
db.events.forEach(x => { need(places, x.place_id, `events/${x.id}`); cites(x, `events/${x.id}`); });
db.person_events.forEach((x, i) => { need(persons, x.person_id, `person_events[${i}]`); need(events, x.event_id, `person_events[${i}]`); cites(x, `person_events[${i}]`); });
need(persons, meta.start, "meta.start");

warnings.forEach(w => console.warn("warn:", w));
if (errors.length) { errors.forEach(e => console.error("error:", e)); process.exit(1); }

const bundle = { ...db, start: meta.start, built: new Date().toISOString().slice(0, 10) };
writeFileSync(join(dir, "bundle.js"), "// Generated by scripts/build.mjs — do not edit by hand.\nwindow.GIANTS = " + JSON.stringify(bundle) + ";\n");
const full = db.persons.filter(p => p.status !== "stub").length;
console.log(`ok: ${db.persons.length} people (${full} full, ${db.persons.length - full} stubs), ${db.relations.length} relations, ${db.works.length} works, ${db.sources.length} sources`);
